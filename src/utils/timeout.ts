/**
 * Операция не уложилась в отведённое время.
 *
 * Текст сообщения видит пользователь — он попадает в всплывающие
 * уведомления как есть, поэтому написан по-человечески. Техническая
 * подробность о том, какая именно операция встала, уходит в лог.
 */
export class TimeoutError extends Error {
    /** Внутреннее имя операции — для логов, не для показа. */
    readonly operation: string;

    constructor(label: string, ms: number) {
        super('Сервер не отвечает. Проверьте соединение и попробуйте ещё раз.');
        this.name = 'TimeoutError';
        this.operation = `${label} (${Math.round(ms / 1000)} с)`;
    }
}

/**
 * Ограничивает ожидание промиса по времени.
 *
 * Зачем: ни один сетевой вызов в приложении не должен висеть бесконечно.
 * Особенно это касается supabase-js — он берёт блокировку через
 * navigator.locks и, если таймаут не задан, ждёт её БЕЗ ОГРАНИЧЕНИЯ.
 * Когда приложение открыто в нескольких вкладках, они конкурируют за эту
 * блокировку, и одна вкладка может застрять навсегда. Снаружи это
 * выглядит как вечный спиннер «Создаём очередь…».
 *
 * Промис не отменяется — отменить чужой нельзя, — но ожидание
 * прекращается, и интерфейс получает внятную ошибку вместо зависания.
 */
export function withTimeout<T>(promise: PromiseLike<T>, ms: number, label: string): Promise<T> {
    return new Promise<T>((resolve, reject) => {
        const timer = setTimeout(() => reject(new TimeoutError(label, ms)), ms);
        Promise.resolve(promise).then(
            (value) => { clearTimeout(timer); resolve(value); },
            (error: unknown) => { clearTimeout(timer); reject(error); },
        );
    });
}

/** Сколько ждём разные операции, в миллисекундах. */
export const TIMEOUTS = {
    /** Анонимный вход: две сетевые ходки плюс возможная блокировка. */
    session: 12_000,
    /** Обычный запрос данных. С запасом на медленный мобильный интернет. */
    request: 20_000,
} as const;
