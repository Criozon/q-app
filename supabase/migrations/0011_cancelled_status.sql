-- =====================================================================
-- Отмена обслуживания
--
-- Раньше у администратора было два исхода: «Закончить» и «Удалить».
-- Оба врут, когда человека вызвали, а он не подошёл.
--
-- «Закончить» записывает serviced_at, и такой участник попадает
-- в measured_service_minutes — в среднюю длительность приёма. То есть
-- каждый неподошедший подмешивал в статистику выдуманный сеанс:
-- вызвали в 14:00, подождали, махнули рукой в 14:05 — и в среднее ушли
-- «пять минут приёма», которых не было. Эта же цифра показывается людям
-- на экране входа.
--
-- «Удалить» сносит строку насовсем: объявился через полчаса — вернуть
-- нечего.
--
-- Отсюда третий исход. Отменённый остаётся в списке, serviced_at ему не
-- ставится (значит, статистику он не портит), а вернуть его можно тем же
-- «Вернуть в очередь», что и закончённого.
-- =====================================================================

alter table public.queue_members
    drop constraint if exists queue_members_status_check;

alter table public.queue_members
    add constraint queue_members_status_check
    check (status in ('waiting', 'called', 'acknowledged', 'in_service', 'serviced', 'cancelled'));

-- Возврат в очередь обнуляет следы прошлого захода — для отменённых
-- ровно так же, как для закончённых. Отдельной ветки не нужно: условие
-- на 'waiting' уже общее.
--
-- Важно, чего здесь НЕТ: ветки для 'cancelled'. serviced_at ей не
-- присваивается намеренно — на этом и держится честность статистики.
